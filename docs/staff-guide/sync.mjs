#!/usr/bin/env node
// Staff guide sync: docs/staff-guide/*.md  ->  one idempotent SQL script for
// the public.staff_guide table (supabase/staff-guide.sql).
//
//   node docs/staff-guide/sync.mjs > /tmp/staff-guide-sync.sql
//
// Then run that SQL in the Supabase SQL editor (project xumsqmhccgfjnlmieqyu),
// or hand it to the Supabase MCP's execute_sql. It needs no secrets: the
// script only reads local files and prints SQL.
//
// What the SQL does, in one transaction:
//   - upserts every article (slug = file name without .md); a row whose
//     content didn't change keeps its updated_at
//   - deletes staff_guide rows whose .md file no longer exists (only rows in
//     staff_guide; nothing else is touched)
//
// Frontmatter (between --- lines at the top of each file):
//   title:    How do I ...?
//   section:  Getting started
//   audience: staff | admin
//   keywords: [word, another word]     (or a comma-separated line)
//   sort:     120                       (optional; lower comes first)
//
// Run with --check to validate the files without printing SQL.

import { readdirSync, readFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const DIR = dirname(fileURLToPath(import.meta.url));
const SLUG_RE = /^[a-z0-9]+(-[a-z0-9]+)*$/;

function parseFrontmatter(text, file) {
  const m = /^---\r?\n([\s\S]*?)\r?\n---\r?\n?([\s\S]*)$/.exec(text);
  if (!m) throw new Error(`${file}: missing --- frontmatter ---`);
  const meta = {};
  for (const line of m[1].split(/\r?\n/)) {
    if (!line.trim() || line.trim().startsWith("#")) continue;
    const kv = /^([A-Za-z_]+)\s*:\s*(.*)$/.exec(line);
    if (!kv) throw new Error(`${file}: can't read frontmatter line "${line}"`);
    let v = kv[2].trim();
    if (/^".*"$|^'.*'$/.test(v)) v = v.slice(1, -1);
    meta[kv[1].toLowerCase()] = v;
  }
  return { meta, body: m[2].replace(/^\s+/, "").replace(/\s+$/, "") + "\n" };
}

function parseKeywords(v) {
  if (!v) return [];
  const inner = v.replace(/^\[/, "").replace(/\]$/, "");
  return inner
    .split(",")
    .map((s) => s.trim().replace(/^["']|["']$/g, ""))
    .filter(Boolean);
}

function loadArticles() {
  const files = readdirSync(DIR)
    .filter((f) => f.endsWith(".md") && f.toLowerCase() !== "readme.md")
    .sort();
  return files.map((file) => {
    const slug = file.replace(/\.md$/, "");
    if (!SLUG_RE.test(slug)) throw new Error(`${file}: file name must be lower-case-with-dashes`);
    const { meta, body } = parseFrontmatter(readFileSync(join(DIR, file), "utf8"), file);
    for (const k of ["title", "section", "audience"]) {
      if (!meta[k]) throw new Error(`${file}: frontmatter needs "${k}"`);
    }
    if (meta.audience !== "staff" && meta.audience !== "admin") {
      throw new Error(`${file}: audience must be staff or admin`);
    }
    const sort = meta.sort == null || meta.sort === "" ? 1000 : Number(meta.sort);
    if (!Number.isInteger(sort)) throw new Error(`${file}: sort must be a whole number`);
    return {
      slug,
      title: meta.title,
      section: meta.section,
      audience: meta.audience,
      keywords: parseKeywords(meta.keywords),
      sort,
      body,
    };
  });
}

// Dollar-quote with a tag that can't appear in the text.
function dq(s) {
  let tag = "sg";
  let n = 0;
  while (s.includes(`$${tag}$`)) tag = `sg${++n}`;
  return `$${tag}$${s}$${tag}$`;
}

function textArray(arr) {
  if (!arr.length) return "'{}'::text[]";
  return `array[${arr.map(dq).join(", ")}]::text[]`;
}

function buildSql(articles) {
  if (!articles.length) throw new Error("No articles found; refusing to generate a delete-everything script.");
  const rows = articles.map(
    (a) =>
      `  (${dq(a.slug)}, ${dq(a.title)}, ${dq(a.section)}, ${dq(a.audience)}, ${dq(a.body)}, ${textArray(a.keywords)}, ${a.sort})`,
  );
  const slugs = articles.map((a) => dq(a.slug)).join(", ");
  return `-- Generated by docs/staff-guide/sync.mjs on ${new Date().toISOString()}.
-- ${articles.length} articles. Idempotent: safe to run again.
begin;

insert into public.staff_guide as g (slug, title, section, audience, body_md, keywords, sort)
values
${rows.join(",\n")}
on conflict (slug) do update set
  title      = excluded.title,
  section    = excluded.section,
  audience   = excluded.audience,
  body_md    = excluded.body_md,
  keywords   = excluded.keywords,
  sort       = excluded.sort,
  updated_at = now()
where (g.title, g.section, g.audience, g.body_md, g.keywords, g.sort)
  is distinct from
  (excluded.title, excluded.section, excluded.audience, excluded.body_md, excluded.keywords, excluded.sort);

delete from public.staff_guide where slug not in (${slugs});

commit;
`;
}

const articles = loadArticles();
const dupTitles = articles.filter((a, i) => articles.findIndex((b) => b.title === a.title) !== i);
if (dupTitles.length) throw new Error(`Duplicate titles: ${dupTitles.map((a) => a.slug).join(", ")}`);
if (process.argv.includes("--check")) {
  console.log(`OK: ${articles.length} articles (${articles.filter((a) => a.audience === "admin").length} admin-only).`);
} else {
  process.stdout.write(buildSql(articles));
}
